#include "../incl/smartgreen.h"

const char *SCHEMA_SQL = 
    "-- Configuración del Sistema\n"
    "CREATE TABLE IF NOT EXISTS config (\n"
    "    key                TEXT    PRIMARY KEY,\n"
    "    value              TEXT    NOT NULL,\n"
    "    last_mod    INTEGER DEFAULT (strftime('%s', 'now'))\n"
    ");\n"
    "\n"
    "-- Zonas\n"
    "CREATE TABLE IF NOT EXISTS zones (\n"
    "    id      INTEGER PRIMARY KEY,\n"
    "    name    TEXT    NOT NULL,\n"
    "    enabled INTEGER DEFAULT 1\n"
    ");\n"
    "\n"
    "-- Parámetros por zonas\n"
    "CREATE TABLE IF NOT EXISTS zone_params (\n"
    "    zone_id             INTEGER PRIMARY KEY,\n"
    "    fan_speed_cmd       INTEGER DEFAULT 3,\n"
    "    target_temp         REAL    DEFAULT 25.0,\n"
    "    humidity_min        REAL    DEFAULT 60.0,\n"
    "    humidity_max        REAL    DEFAULT 70.0,\n"
    "    integral            REAL    DEFAULT 00.0,\n"
    "    pump_on             INTEGER DEFAULT 0,\n"
    "    humidity_control    INTEGER DEFAULT 0,\n"
    "    cool_fan_mode       TEXT    DEFAULT 'AUTO',\n"
    "    drain_valve         TEXT    DEFAULT 'close',\n"
    "    solenoid            TEXT    DEFAULT 'on',\n"
    "    on_off              TEXT    DEFAULT 'OFF',\n"
    "    inmediate_drain     TEXT    DEFAULT 'no',\n"
    "    prewet_in_progress  TEXT    DEFAULT 'no',\n"
    "    last_prewet         INTEGER DEFAULT '0',\n"
    "    last_drain          INTEGER DEFAULT '0',\n"
    "    last_pump_time      INTEGER DEFAULT '0',\n"
    "    FOREIGN KEY (zone_id) REFERENCES zones(id)\n"
    ");\n"
    "\n"
    "-- Estado actual de los coolers\n"
    "CREATE TABLE IF NOT EXISTS cooler_state (\n"
    "    unit_id                INTEGER PRIMARY KEY,\n"
    "    zone_id                INTEGER,\n"
    "    is_extractor           INTEGER DEFAULT 0,\n"
    "    error_count            INTEGER DEFAULT 0,\n"
    "    drain_valve_open       INTEGER DEFAULT 0,\n"
    "    drain_valve_confirm    INTEGER DEFAULT 0,\n"
    "    cool_mode_on           INTEGER DEFAULT 0,\n"
    "    fan_on                 INTEGER DEFAULT 0,\n"
    "    fault_present          INTEGER DEFAULT 0,\n"
    "    inlet_valve_open       INTEGER DEFAULT 0,\n"
    "    actual_fan_speed       INTEGER DEFAULT 0,\n"
    "    fan_speed_confirmed    INTEGER DEFAULT 0,\n"
    "    most_recent_fault      INTEGER DEFAULT 0,\n"
    "    water_present          INTEGER DEFAULT 0,\n"
    "    pump_on                INTEGER DEFAULT 0,\n"
    "    solenoid_on            INTEGER DEFAULT 0,\n"
    "    salinity_ppm           REAL    DEFAULT 0.00,\n"
    "    salinity_us            REAL    DEFAULT 0.00,\n"
    "    last_read              INTEGER DEFAULT 0,\n"
    "    last_mod               INTEGER DEFAULT 0,\n"
    "    alarm_fault            INTEGER DEFAULT 0,\n"
    "    alarm_salinity         INTEGER DEFAULT 0,\n"
    "    alarm_water            INTEGER DEFAULT 0,\n"
    "    alarm_comms            INTEGER DEFAULT 0,\n"
    "    alarm_warranty         INTEGER DEFAULT 0,\n"
    "    alarm_maint_opening    INTEGER DEFAULT 0,\n"
    "    alarm_maint_closing    INTEGER DEFAULT 0,\n"
    "    alarm_maint_legionella INTEGER DEFAULT 0,\n"
    "    hours_running          REAL    DEFAULT 0.00,\n"
    "    install_date           INTEGER DEFAULT 0,\n"
    "    warranty_months        INTEGER DEFAULT 24,\n"
    "    disabled               INTEGER DEFAULT 0,\n"
    "    ramp_rate              INTEGER DEFAULT 0,\n"
    "    cold_starts            INTEGER DEFAULT 0,\n"
    "    fan_starts             INTEGER DEFAULT 0,\n"
    "    fan_hours              INTEGER DEFAULT 0,\n"
    "    tank_drains            INTEGER DEFAULT 0,\n"
    "    avg_tank_fill          INTEGER DEFAULT 0,\n"
    "    fan_speed_z1           INTEGER DEFAULT 0,\n"
    "    fan_speed_z2           INTEGER DEFAULT 0,\n"
    "    fan_speed_z3           INTEGER DEFAULT 0,\n"
    "    fan_speed_z4           INTEGER DEFAULT 0,\n"
    "    fan_speed_z5           INTEGER DEFAULT 0,\n"
    "    extended_status        INTEGER DEFAULT 0,\n"
    "    modbus_addr            INTEGER DEFAULT 0,\n"
    "    r0_config              INTEGER DEFAULT 0,\n"
    "    prev_fan_starts        INTEGER DEFAULT 0,\n"
    "    fan_zero_ticks         INTEGER DEFAULT 0,\n"
    "    fan_running            INTEGER DEFAULT 0,\n"
    "    last_off               INTEGER DEFAULT 0,\n"
    "    FOREIGN KEY (zone_id) REFERENCES zones(id)\n"
    ");\n"
    "\n"
    "-- Estado actual de los sensores\n"
    "CREATE TABLE IF NOT EXISTS sensor_state (\n"
    "    sensor_id              INTEGER PRIMARY KEY,\n"
    "    zone_id                INTEGER,\n"
    "    type                   TEXT    DEFAULT 'INT',\n"
    "    name                   TEXT,\n"
    "    temperature            REAL    DEFAULT -200.00,\n"
    "    humidity               REAL    DEFAULT -200.00,\n"
    "    flags                  INTEGER DEFAULT 0,\n"
    "    valid                  INTEGER DEFAULT 0,\n"
    "    offset_val             INTEGER DEFAULT 0,\n"
    "    humidity_offset_val    INTEGER DEFAULT 0,\n"
    "    error_count            INTEGER DEFAULT 0,\n"
    "    last_read              INTEGER DEFAULT 0,\n"
    "    last_mod               INTEGER DEFAULT 0,\n"
    "    alarm_signal           INTEGER DEFAULT 0,\n"
    "    alarm_temp             INTEGER DEFAULT 0,\n"
    "    disabled               INTEGER DEFAULT 0\n"
    ");\n"
    "\n"
    "-- Relación sensor -> zona\n"
    "CREATE TABLE IF NOT EXISTS sensor_zone (\n"
    "    sensor_id   INTEGER,\n"
    "    zone_id     INTEGER,\n"
    "    PRIMARY KEY (sensor_id, zone_id)\n"
    ");\n"
    "\n"
    "-- Histórico de lecturas\n"
    "CREATE TABLE IF NOT EXISTS history (\n"
    "    id              INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    timestamp       INTEGER NOT NULL,\n"
    "    unit_id         INTEGER,\n"
    "    zone_id         INTEGER,\n"
    "    device_type     TEXT,\n"
    "    temp_raw        INTEGER,\n"
    "    hum_raw         INTEGER,\n"
    "    fan_speed_cmd   INTEGER,\n"
    "    target_temp     REAL,\n"
    "    humidity_min    REAL,\n"
    "    humidity_max    REAL,\n"
    "    integral        REAL,\n"
    "    pump_on         INTEGER,\n"
    "    cool_fan_mode   TEXT,\n"
    "    water_present   INTEGER,\n"
    "    salinity_ppm    REAL,\n"
    "    salinity_us     REAL,\n"
    "    drain_open      INTEGER,\n"
    "    solenoid_on     TEXT,\n"
    "    on_off          INT,\n"
    "    fault_code      INTEGER\n"
    ");\n"
    "\n"
    "-- Log de errores\n"
    "CREATE TABLE IF NOT EXISTS error_log (\n"
    "    id          INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    unit_id     INTEGER DEFAULT 0,\n"
    "    timestamp   INTEGER NOT NULL,\n"
    "    level       TEXT    DEFAULT 'ERROR',\n"
    "    message     TEXT    NOT NULL\n"
    ");\n"
    "\n"
    "-- Log de fallos de coolers\n"
    "CREATE TABLE IF NOT EXISTS fault_log (\n"
    "    id              INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    unit_id         INTEGER NOT NULL,\n"
    "    fault_code      INTEGER NOT NULL,\n"
    "    fault_present   INTEGER DEFAULT 1,\n"
    "    time_created    INTEGER NOT NULL,\n"
    "    time_cleared    INTEGER DEFAULT 0\n"
    ");\n"
    "\n"
    "-- Scheduler de encendido/apagado\n"
    "CREATE TABLE IF NOT EXISTS scheduler (\n"
    "    id      INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    name    TEXT,\n"
    "    zone_id INTEGER DEFAULT 0,\n"
    "    active  INTEGER DEFAULT 1,\n"
    "    action  TEXT    NOT NULL,\n"
    "    hour    TEXT    NOT NULL,\n"
    "    mon     INTEGER DEFAULT 0,\n"
    "    tue     INTEGER DEFAULT 0,\n"
    "    wed     INTEGER DEFAULT 0,\n"
    "    thu     INTEGER DEFAULT 0,\n"
    "    fri     INTEGER DEFAULT 0,\n"
    "    sat     INTEGER DEFAULT 0,\n"
    "    sun     INTEGER DEFAULT 0,\n"
    "    mode    TEXT    NOT NULL,\n"
    "    target_temp     REAL\n"
    ");\n"
    "\n"
    "-- Exclusiones del Scheduler\n"
    "CREATE TABLE IF NOT EXISTS scheduler_exclusions (\n"
    "    id INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    date TEXT NOT NULL\n"
    ");\n"
    "\n"
    "-- Tabla para historial de mantenimiento\n"
    "CREATE TABLE IF NOT EXISTS maintenance_log (\n"
    "   id              INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "   unit_id         INTEGER NOT NULL,\n"
    "   timestamp       INTEGER NOT NULL,\n"
    "   type            TEXT NOT NULL,\n"
    "   description     TEXT,\n"
    "   technician      TEXT,\n"
    "   next_service    INTEGER DEFAULT 0\n"
    ");\n"
    "\n"
    "-- Tabla de usuarios\n"
    "CREATE TABLE IF NOT EXISTS users (\n"
    "    id         INTEGER PRIMARY KEY AUTOINCREMENT,\n"
    "    username   TEXT    NOT NULL UNIQUE,\n"
    "    password   TEXT    NOT NULL,\n"
    "    role       TEXT    DEFAULT 'operator',\n"
    "    active     INTEGER DEFAULT 1\n"
    ");\n"
    "\n"
    "-- Índices\n"
    "CREATE INDEX IF NOT EXISTS idx_history_timestamp ON history(timestamp);\n"
    "CREATE INDEX IF NOT EXISTS idx_history_zone ON history(zone_id);\n"
    "CREATE INDEX IF NOT EXISTS idx_error_timestamp ON error_log(timestamp);\n"
    "CREATE INDEX IF NOT EXISTS idx_fault_unit ON fault_log(unit_id);\n";
